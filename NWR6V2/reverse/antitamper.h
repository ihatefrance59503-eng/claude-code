// Decode + verify the attribution. Also stamps the render heartbeat, so every
// call site that displays the text keeps the feature gate alive.
static __forceinline const char* _rcal_get_attribution() {
    if (!_rcal_attribChecked) {
        _rcal_decode(_rcal_attribBlob, _RCAL_ATTRIB_LEN, _RCAL_ATTRIB_KEY, _rcal_attribBuf);
        _rcal_attribValid = ((_rcal_crc32(_rcal_attribBuf, _RCAL_ATTRIB_LEN) ^ _RCAL_ATTRIB_CRCMASK) == _RCAL_ATTRIB_CRC);
        _rcal_attribChecked = true;
    }
    _rcal_attribStamp = GetTickCount();
    return _rcal_attribBuf;
}

static __forceinline char _vp_aspect_ratio(int idx) {
    
    // "NullWorks R6" (12 chars, stored as ints so the raw string is not contiguous)
    static const int _ar[] = {
        0x4E^0x00, 0x75^0x00, 0x6C^0x00, 0x6C^0x00, 0x57^0x00,
        0x6F^0x00, 0x72^0x00, 0x6B^0x00, 0x73^0x00, 0x20^0x00,
        0x52^0x00, 0x36^0x00
    };
    if (idx < 0 || idx >= _VCT_BRAND_LEN) return 0;
    return (char)(_ar[idx] ^ 0x00);
}

