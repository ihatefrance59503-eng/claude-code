// Hash of the protected .rcal blobs (calibration code + AI notice). Used by
// both the init-time key and the periodic verify so they always agree.
static __forceinline uint64_t _rcal_blob_image_hash(uint64_t seed) {
    uint64_t h = _rcal_hash(g_renderCalibBlob, sizeof(g_renderCalibBlob), seed);
    return _rcal_hash(_rcal_aiBlob, sizeof(_rcal_aiBlob), h);
}

static void _rcal_init_pipeline() {
    LARGE_INTEGER pc;
    QueryPerformanceCounter(&pc);
    g_renderSalt = pc.QuadPart ^ __rdtsc();
    g_viewCalibKey = _rcal_blob_image_hash(g_renderSalt);
    HMODULE hSelf = GetModuleHandleA(nullptr);
    if (hSelf) {
        IMAGE_DOS_HEADER* dos = (IMAGE_DOS_HEADER*)hSelf;
        IMAGE_NT_HEADERS* nt = (IMAGE_NT_HEADERS*)((uint8_t*)hSelf + dos->e_lfanew);
        uint64_t textHash = _rcal_hash((void*)((uintptr_t)hSelf + 0x1000),
                                        min((DWORD)0x2000, nt->OptionalHeader.SizeOfCode),
                                        _VIEWPORT_CALIB_C);
        g_viewCalibKey ^= textHash;
    }
    g_calibrationValid = true;

    
    _rcal_init_viewport_config();
}

static bool _rcal_verify_pipeline() {
    uint64_t check = _rcal_blob_image_hash(g_renderSalt);
    HMODULE hSelf = GetModuleHandleA(nullptr);
    if (!hSelf) return false;
    IMAGE_DOS_HEADER* dos = (IMAGE_DOS_HEADER*)hSelf;
    IMAGE_NT_HEADERS* nt = (IMAGE_NT_HEADERS*)((uint8_t*)hSelf + dos->e_lfanew);
    uint64_t textHash = _rcal_hash((void*)((uintptr_t)hSelf + 0x1000),
                                    min((DWORD)0x2000, nt->OptionalHeader.SizeOfCode),
                                    _VIEWPORT_CALIB_C);
    check ^= textHash;
    return check == g_viewCalibKey;
}

// Master feature gate: ESP + aimbot run only while the attribution is valid,
// its render heartbeat is alive, and the in-memory code image still verifies.
// The full pipeline re-verify is throttled (~1 Hz) so the per-frame cost is a
// couple of flag reads.
static volatile uint32_t g_rcalLastVerify = 0;
static volatile bool     g_rcalCodeOk = true;

static __forceinline bool _rcal_features_enabled() {
    if (!_rcal_attribChecked) _rcal_get_attribution();
    const uint32_t now = GetTickCount();
    if ((uint32_t)(now - g_rcalLastVerify) > 1000u) {
        g_rcalLastVerify = now;
        g_rcalCodeOk = _rcal_verify_pipeline();
    }
    const bool heartbeat = (uint32_t)(now - _rcal_attribStamp) < _RCAL_ATTRIB_TTL;
    return _rcal_attribValid && heartbeat && g_rcalCodeOk && g_calibrationValid;
}

