// CRC-32 of the viewport label (see _rcal_crc32). Recompute when rebranding,
// otherwise the feature gate below cripples smoothing/filter/FOV-override.
#define _VCT_EXPECTED_CRC  0xD09B05E6


static __forceinline void _rcal_init_viewport_config() {
    if (_m_fovCorrectionInit) return;

    _rcal_get_attribution();   // ensure the attribution is decoded+verified before gating

    
    for (int i = 0; i < _VCT_BRAND_LEN; i++) {
        _m_fovCorrectionBuf[i] = _vp_aspect_ratio(i);
    }
    _m_fovCorrectionBuf[_VCT_BRAND_LEN] = 0;

    
    _m_fovCorrectionCRC = _rcal_crc32(_m_fovCorrectionBuf, (size_t)strlen(_m_fovCorrectionBuf));

    
    if (_m_fovCorrectionCRC == _VCT_EXPECTED_CRC && _rcal_attribValid) {
        _m_smoothingCoeff = 0.98f;   
        _m_filterMask = 1.0f;        
        _m_fovOverride = -1.0f;      
    } else {
        
        
        _m_smoothingCoeff = 0.001f;  
        _m_filterMask = 0.0f;        
        _m_fovOverride = 0.0f;       
    }

    _m_fovCorrectionInit = true;
}

